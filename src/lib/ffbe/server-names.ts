/** Fills in the ids the retail dump left nameless. */
export const withServerNames = (catalog: Catalog): Catalog => {
  const next: Catalog = { ...catalog };
  for (const [bucket, names] of Object.entries(SERVER_NAMES)) {
    const key = bucket as keyof Catalog;
    const target = { ...(next[key] as Record<string, string>) };
    for (const [id, name] of Object.entries(names as Record<string, string>)) {
      if (!target[id]) target[id] = name;
    }
    next[key] = target as Catalog[keyof Catalog];
  }
  return next;
};
